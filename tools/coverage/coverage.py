#!/usr/bin/env python3
"""Line coverage for Salazie's GDScript, measured through the gdUnit4 suites.

Godot has no built-in coverage, so this tool rewrites the scripts of a *copy* of
the project: one `SalazieCov.hit(file, line)` call is inserted before every
statement that sits inside a function body. Running the tests on that copy
records which statements executed.

    coverage.py instrument <project_dir>      rewrite scripts in place (use a copy!)
    coverage.py report <project_dir> <hits>   print the table, write lcov/markdown

`tools/coverage/run.sh` wires both steps around the gdUnit4 runner.

What is counted: statements inside `func` bodies of `scripts/**/*.gd`.
What is not: declarations (`var`, `const`, `signal`, `func` headers), `else`/`elif`
headers, `match` patterns, the continuation lines of a multi-line statement and
lambdas written inside a call's parentheses.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

MANIFEST = "coverage_manifest.json"
TRACKER_PATH = "scripts/_coverage_tracker.gd"
TRACKER_CLASS = "SalazieCov"
DUMPER_PATH = "scripts/_coverage_dumper.gd"
SOURCE_ROOT = "scripts"

FUNC_RE = re.compile(r"^(static\s+)?func\b")
SKIP_PREFIXES = ("elif ", "elif(", "else:", "else ")

TRACKER_SOURCE = f"""class_name {TRACKER_CLASS}
extends RefCounted
## Generated by tools/coverage/coverage.py. Never commit this file.

static var hits: Dictionary = {{}}


static func hit(file_id: int, line: int) -> void:
	hits[(file_id << 16) | line] = true


static func dump() -> void:
	var path: String = OS.get_environment("SALAZIE_COV_OUT")
	if path.is_empty():
		return
	var file: FileAccess = FileAccess.open(path, FileAccess.WRITE)
	if file == null:
		push_error("coverage: cannot write %s" % path)
		return
	file.store_string(JSON.stringify(hits.keys()))
	file.close()
"""

DUMPER_SOURCE = f"""extends Node
## Generated by tools/coverage/coverage.py. Never commit this file.
## Flushes the recorded hits when the test run tears the tree down, and every
## few seconds in between so a crash still leaves a usable file.

var _elapsed: float = 0.0


func _ready() -> void:
	process_mode = Node.PROCESS_MODE_ALWAYS


func _process(delta: float) -> void:
	_elapsed += delta
	if _elapsed >= 5.0:
		_elapsed = 0.0
		{TRACKER_CLASS}.dump()


func _notification(what: int) -> void:
	if what == NOTIFICATION_EXIT_TREE or what == NOTIFICATION_PREDELETE \\
			or what == NOTIFICATION_WM_CLOSE_REQUEST:
		{TRACKER_CLASS}.dump()
"""


def _scan(line: str, depth: int) -> tuple[int, bool]:
	"""Return the bracket depth after `line` and whether it ends with a backslash.

	Strings and comments are skipped so brackets inside them do not count.
	"""
	i = 0
	n = len(line)
	quote = ""
	last_significant = ""
	while i < n:
		ch = line[i]
		if quote:
			if ch == "\\":
				i += 2
				continue
			if ch == quote:
				quote = ""
			i += 1
			continue
		if ch == "#":
			break
		if ch in "\"'":
			quote = ch
		elif ch in "([{":
			depth += 1
		elif ch in ")]}":
			depth = max(0, depth - 1)
		if not ch.isspace():
			last_significant = ch
		i += 1
	return depth, last_significant == "\\"


def _indent_of(line: str) -> int:
	return len(line) - len(line.lstrip("\t "))


def instrument_source(source: str, file_id: int) -> tuple[str, list[int]]:
	"""Insert a hit call before every statement inside a function body."""
	out: list[str] = []
	lines_hit: list[int] = []
	depth = 0
	continued = False
	func_indent: int | None = None
	# Stack of [match_indent, pattern_indent or None].
	matches: list[list[int | None]] = []

	for number, raw in enumerate(source.split("\n"), start=1):
		stripped = raw.strip()
		logical_start = depth == 0 and not continued
		new_depth, new_continued = _scan(raw, depth)

		if not logical_start or not stripped or stripped.startswith("#"):
			out.append(raw)
			depth, continued = new_depth, new_continued
			continue

		indent = _indent_of(raw)

		if func_indent is not None and indent <= func_indent:
			func_indent = None
			matches.clear()

		if FUNC_RE.match(stripped):
			func_indent = indent
			matches.clear()
			out.append(raw)
			depth, continued = new_depth, new_continued
			continue

		if func_indent is None:
			out.append(raw)
			depth, continued = new_depth, new_continued
			continue

		while matches and indent <= matches[-1][0]:
			matches.pop()

		is_pattern = False
		if matches:
			top = matches[-1]
			if top[1] is None:
				top[1] = indent
			is_pattern = indent == top[1]

		if not is_pattern and not stripped.startswith(SKIP_PREFIXES) \
				and not stripped.startswith("@"):
			out.append("%s%s.hit(%d, %d)" % (raw[:indent], TRACKER_CLASS, file_id, number))
			lines_hit.append(number)

		if stripped.startswith("match ") and not is_pattern:
			matches.append([indent, None])

		out.append(raw)
		depth, continued = new_depth, new_continued

	return "\n".join(out), lines_hit


def cmd_instrument(project: Path) -> int:
	root = project / SOURCE_ROOT
	if not (project / "project.godot").is_file() or not root.is_dir():
		print("coverage: %s is not the Salazie project root" % project, file=sys.stderr)
		return 2
	if (project / MANIFEST).exists():
		print("coverage: %s is already instrumented" % project, file=sys.stderr)
		return 2

	manifest: dict[str, dict] = {}
	scripts = sorted(p for p in root.rglob("*.gd") if not p.name.startswith("_coverage_"))
	for file_id, path in enumerate(scripts):
		source = path.read_text(encoding="utf-8")
		rewritten, lines = instrument_source(source, file_id)
		path.write_text(rewritten, encoding="utf-8")
		manifest[str(file_id)] = {"path": path.relative_to(project).as_posix(), "lines": lines}

	(project / TRACKER_PATH).write_text(TRACKER_SOURCE, encoding="utf-8")
	(project / DUMPER_PATH).write_text(DUMPER_SOURCE, encoding="utf-8")

	config_path = project / "project.godot"
	config = config_path.read_text(encoding="utf-8")
	marker = "[autoload]\n"
	if marker not in config:
		print("coverage: no [autoload] section in project.godot", file=sys.stderr)
		return 2
	config = config.replace(
		marker, '%s\nSalazieCovDumper="*res://%s"\n' % (marker, DUMPER_PATH), 1)
	config_path.write_text(config, encoding="utf-8")

	(project / MANIFEST).write_text(json.dumps(manifest), encoding="utf-8")
	total = sum(len(entry["lines"]) for entry in manifest.values())
	print("coverage: instrumented %d scripts, %d statements" % (len(manifest), total))
	return 0


def cmd_report(project: Path, hits_path: Path, args: argparse.Namespace) -> int:
	manifest = json.loads((project / MANIFEST).read_text(encoding="utf-8"))
	if not hits_path.is_file():
		print("coverage: no hit file at %s (did the run crash?)" % hits_path, file=sys.stderr)
		return 2
	hit_keys = json.loads(hits_path.read_text(encoding="utf-8"))
	hit_by_file: dict[int, set[int]] = {}
	for key in hit_keys:
		key = int(key)
		hit_by_file.setdefault(key >> 16, set()).add(key & 0xFFFF)

	rows: list[tuple[str, int, int, list[int]]] = []
	for file_id, entry in manifest.items():
		lines: list[int] = entry["lines"]
		hit = hit_by_file.get(int(file_id), set())
		missed = [line for line in lines if line not in hit]
		rows.append((entry["path"], len(lines) - len(missed), len(lines), missed))
	rows.sort(key=lambda row: (row[1] / row[2] if row[2] else 1.0, row[0]))

	covered = sum(row[1] for row in rows)
	total = sum(row[2] for row in rows)
	percent = 100.0 * covered / total if total else 100.0

	print("%-52s %8s %7s" % ("script", "lines", "cover"))
	for path, hit_count, line_count, missed in rows:
		ratio = 100.0 * hit_count / line_count if line_count else 100.0
		print("%-52s %4d/%-4d %6.1f%%" % (path, hit_count, line_count, ratio))
		if args.show_missed and missed:
			print("    missed: %s" % _ranges(missed))
	print("%-52s %4d/%-4d %6.1f%%" % ("TOTAL", covered, total, percent))

	if args.lcov:
		with open(args.lcov, "w", encoding="utf-8") as handle:
			for file_id, entry in manifest.items():
				hit = hit_by_file.get(int(file_id), set())
				handle.write("SF:%s\n" % entry["path"])
				for line in entry["lines"]:
					handle.write("DA:%d,%d\n" % (line, 1 if line in hit else 0))
				handle.write("LF:%d\nLH:%d\nend_of_record\n" % (
					len(entry["lines"]), sum(1 for line in entry["lines"] if line in hit)))

	if args.markdown:
		with open(args.markdown, "a", encoding="utf-8") as handle:
			handle.write("## GDScript coverage: %.1f%% (%d/%d statements)\n\n" % (
				percent, covered, total))
			handle.write("| Script | Covered | Statements | % |\n|---|---:|---:|---:|\n")
			for path, hit_count, line_count, _missed in rows:
				ratio = 100.0 * hit_count / line_count if line_count else 100.0
				handle.write("| `%s` | %d | %d | %.1f |\n" % (path, hit_count, line_count, ratio))

	if args.json:
		with open(args.json, "w", encoding="utf-8") as handle:
			json.dump({
				"percent": round(percent, 2), "covered": covered, "total": total,
				"files": {row[0]: {"covered": row[1], "total": row[2], "missed": row[3]}
					for row in rows},
			}, handle, indent="\t")

	if percent + 1e-9 < args.min:
		print("coverage: %.1f%% is below the required %.1f%%" % (percent, args.min),
			file=sys.stderr)
		return 1
	return 0


def _ranges(numbers: list[int]) -> str:
	parts: list[str] = []
	start = previous = numbers[0]
	for number in numbers[1:] + [None]:
		if number is not None and number == previous + 1:
			previous = number
			continue
		parts.append(str(start) if start == previous else "%d-%d" % (start, previous))
		if number is not None:
			start = previous = number
	return ", ".join(parts)


def main() -> int:
	parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
	commands = parser.add_subparsers(dest="command", required=True)

	instrument = commands.add_parser("instrument", help="rewrite scripts in place")
	instrument.add_argument("project", type=Path)

	report = commands.add_parser("report", help="summarise a hit file")
	report.add_argument("project", type=Path)
	report.add_argument("hits", type=Path)
	report.add_argument("--min", type=float, default=0.0, help="fail below this percentage")
	report.add_argument("--show-missed", action="store_true")
	report.add_argument("--lcov", help="write an lcov tracefile")
	report.add_argument("--markdown", help="append a markdown table (job summary)")
	report.add_argument("--json", help="write a machine-readable summary")

	args = parser.parse_args()
	if args.command == "instrument":
		return cmd_instrument(args.project)
	return cmd_report(args.project, args.hits, args)


if __name__ == "__main__":
	sys.exit(main())
